import sys,re
from playwright.sync_api import sync_playwright
U=sys.argv[1]; shots=len(sys.argv)<3; errs=[]
BAD=re.compile(r'peptide|mcg|dose|vial|syringe|protocol|inventory|reconstitut|passcode',re.I)
with sync_playwright() as p:
    b=p.chromium.launch(executable_path='/usr/bin/google-chrome',args=['--no-sandbox'])
    pg=b.new_page(viewport={'width':400,'height':860},device_scale_factor=2)
    pg.on('pageerror',lambda e:errs.append(str(e))); pg.on('console',lambda m:m.type=='error' and errs.append(m.text))
    pg.goto(U); pg.wait_for_selector('.tnow',timeout=30000)
    vis=pg.evaluate('document.body.innerText'); print('title:',pg.title(),'| decoy leaks:',BAD.findall(vis))
    print('toggle visible:',pg.is_visible('.tseg'),'| location:',pg.inner_text('#tloc'))
    pg.wait_for_selector('.wnow',timeout=30000); print('GO:',pg.inner_text('.kgo').replace('\n',' '))
    ks=pg.evaluate("[5,11.5,12,14,16,18,20,22,25,28,35].map(k=>[k,(window.__ks||(()=>null))(k)])"); print('daily sizes:',[x.split('·')[-1].strip() for x in pg.locator('.kw').all_inner_texts()]); print('Wind now:',pg.inner_text('.wnow').replace('\n',' '),'| hourly pts:',pg.evaluate("document.querySelectorAll('.kh').length"),'kiteable:',pg.evaluate("document.querySelectorAll('.kh.kite').length"),'| daily rows:',pg.evaluate("document.querySelectorAll('.krow').length"))
    print('Key Largo:',pg.inner_text('.tnow').replace('\n',' '),'|',pg.inner_text('.tnext').replace('\n',' '),'|',pg.inner_text('.tfoot').replace('\n',' '))
    if shots: pg.screenshot(path='screenshots/10-tide-keylargo.png',full_page=True)
    pg.click('.kunit [data-u=mph]'); pg.wait_for_selector('.wnow'); print('mph:',pg.inner_text('.wbig')); pg.click('.kunit [data-u=kn]'); pg.wait_for_selector('.wnow')
    if shots: pg.screenshot(path='screenshots/10-tide-keylargo.png',full_page=True)
    print('keypad before taps:',pg.is_visible('#lock'))
    for i in range(3): pg.click('#tbrand')
    print('triple-tap logo (removed) opens keypad:',pg.is_visible('#lock'))
    hb=pg.locator('.khero').bounding_box()
    for name,(fx,fy) in {'sky top-left':(.08,.1),'sky right':(.9,.25),'below rider':(.5,.8),'wind number':(.4,.75)}.items():
        pg.mouse.click(hb['x']+hb['width']*fx,hb['y']+hb['height']*fy); pg.wait_for_timeout(100)
        print(f'tap {name}: keypad={pg.is_visible("#lock")}')
    r=pg.evaluate('__riderRect()'); print('rider box px:',{k:round(v) for k,v in r.items()})
    pg.mouse.click(hb['x']+(r['x0']+r['x1'])/2,hb['y']+(r['y0']+r['y1'])/2); pg.wait_for_timeout(200); print('tap rider: keypad=',pg.is_visible('#lock'))
    if shots: pg.screenshot(path='screenshots/11-hidden-keypad.png')
    pg.click('#lkCancel'); print('cancel back to tides:',not pg.is_visible('#lock') and pg.is_visible('#tide'))
    pg.mouse.click(hb['x']+(r['x0']+r['x1'])/2,hb['y']+(r['y0']+r['y1'])/2); pg.wait_for_timeout(200)
    for k in '1004': pg.click(f'#pad [data-k="{k}"]')
    pg.wait_for_timeout(600); print('unlocked tracker:',pg.is_visible('main') and not pg.is_visible('#tide'), '| header:', pg.inner_text('header').split('\n')[0])
    pg.click('#ham'); pg.wait_for_timeout(300); pg.click('#drawer >> text=Lock now'); pg.wait_for_timeout(500)
    print('lock now -> tide screen:',pg.is_visible('#tide') and not pg.is_visible('#lock') and not pg.is_visible('main'))
    pg.reload(); pg.wait_for_timeout(1500); print('reload after lock: still on tides:', pg.is_visible('#tide'))
    b.close()
print('ERRORS',errs)
